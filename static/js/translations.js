window.i18n = {
    translations: translations,
    currentLang: localStorage.getItem('selectedLanguage') || 'en',

    setLanguage: function (lang) {
        this.currentLang = lang;
        localStorage.setItem('selectedLanguage', lang);
        this.applyTranslations();

        // Notify server about language preference if logged in
        fetch('/update_language', {
            method: 'POST',
            headers: { 'Content-Type': 'application/json' },
            body: JSON.stringify({ language: lang })
        }).catch(err => console.log('Lang update error:', err));
    },

    translate: function (key) {
        return this.translations[this.currentLang][key] || key;
    },

    applyTranslations: function () {
        document.querySelectorAll('[data-i18n]').forEach(el => {
            const key = el.getAttribute('data-i18n');
            if (this.translations[this.currentLang][key]) {
                if (el.tagName === 'INPUT' && (el.type === 'text' || el.type === 'search' || el.placeholder)) {
                    el.placeholder = this.translations[this.currentLang][key];
                } else {
                    el.textContent = this.translations[this.currentLang][key];
                }
            }
        });

        // Update document title if applicable
        document.documentElement.lang = this.currentLang;
    }
};

document.addEventListener('DOMContentLoaded', () => {
    window.i18n.applyTranslations();
});
